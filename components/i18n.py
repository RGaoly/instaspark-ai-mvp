def get_language() -> str:
    return str(st.session_state.get("language", "en"))


def is_zh() -> bool:
    return get_language() == "zh"


def set_language(language: str) -> None:
    if language not in {"en", "zh"}:
        raise ValueError(f"Unsupported language: {language}")
    st.session_state.language = language


def translate(key: Any, *, language: str | None = None, **kwargs: Any) -> str:
    """Exact-key translation. Use for individual UI strings via t()."""
    text = str(key)
    selected = language or get_language()
    translated = ZH.get(text, text) if selected == "zh" else text
    return translated.format(**kwargs) if kwargs else translated


import re as _re

_ZH_PATTERN: _re.Pattern[str] | None = None


def _build_pattern() -> _re.Pattern[str]:
    """Build a compiled regex pattern for batch substring replacement."""
    global _ZH_PATTERN
    if _ZH_PATTERN is None:
        sorted_keys = sorted(ZH, key=len, reverse=True)
        _ZH_PATTERN = _re.compile("|".join(_re.escape(k) for k in sorted_keys))
    return _ZH_PATTERN


def localize_text(value: Any, *, language: str | None = None) -> str:
    """Batch substring translation via compiled regex. Use for HTML blocks via lhtml()."""
    text = str(value)
    selected = language or get_language()
    if selected != "zh":
        return text
    pattern = _build_pattern()
    return pattern.sub(lambda m: ZH[m.group()], text)


def localize_html(value: str) -> str:
    return localize_text(value)


